import { test, expect } from "@playwright/test"
import type { Page } from "@playwright/test"

const harness = "/tests/browser/harness.html"
async function start(page: Page, mode = "normal") {
  await page.goto(`${harness}?mode=${mode}`)
  await page.getByRole("radio", { name: "technical-objective-1", exact: false }).check()
  await page.getByRole("button", { name: "Commencer", exact: true }).click()
}
async function complete(page: Page) {
  await page.getByLabel("technical-answer", { exact: true }).fill("value-1")
  await page.getByTestId("validate-step").click()
  await page.getByLabel("technical-answer", { exact: true }).fill("value-2")
  await page.getByTestId("validate-step").click()
  await expect(page.locator("main")).toHaveAttribute("data-view", "summary")
}

test("production shows the S01 demonstration catalogue, safe text and no test content", async ({ page }) => {
  const requests: string[] = []
  page.on("request", (request) => { if (["fetch", "xhr"].includes(request.resourceType())) requests.push(request.url()) })
  await page.goto("/")
  await expect(page.getByRole("heading", { level: 1 })).toHaveCount(1)
  await expect(page.getByRole("heading", { name: "Aucun objectif disponible" })).toHaveCount(0)
  await expect(page.getByRole("radio", { name: /Préparer ma participation à un atelier numérique/ })).toBeVisible()
  await expect(page.getByRole("button", { name: "Commencer" })).toBeVisible()
  await expect(page.locator("body")).not.toContainText("technical-")
  expect(requests).toEqual([])
  await page.screenshot({ path: "test-results/phase5-production.png", fullPage: true })
})

