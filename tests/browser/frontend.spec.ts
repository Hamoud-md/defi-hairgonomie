test("hidden answers remain available for correction and do not silently return to final decisions", async ({ page }) => {
  await start(page)
  const preference = page.getByLabel("technical-preference-1", { exact: true })
  await preference.selectOption("value-reorder")
  // Step-tail is moved before step-1; returning selects it without mutating answers.
  await page.getByRole("button", { name: "Retour", exact: true }).click()
  await page.getByLabel("technical-answer", { exact: true }).fill("tail-retained")
  await page.getByTestId("validate-step").click()
  await preference.selectOption("value-alt")
  await expect(page.getByTestId("invalidated-answers")).toContainText("tail-retained")
  await expect(page.getByTestId("invalidated-answers")).toContainText("technical-hide-tail")
  await preference.selectOption("value-1")
  await expect(page.getByTestId("invalidated-answers")).toContainText("tail-retained")
  await page.getByTestId("invalidated-answers").getByRole("button", { name: "Modifier cette réponse" }).click()
  await expect(page.getByLabel("technical-answer", { exact: true })).toHaveValue("tail-retained")
  await page.getByLabel("technical-answer", { exact: true }).fill("tail-corrected")
  await page.getByTestId("save-revision").click()
  await expect(page.getByTestId("invalidated-answers")).toHaveCount(0)
  await complete(page)
  await expect(page.getByText("tail-corrected", { exact: true })).toBeVisible()
})

