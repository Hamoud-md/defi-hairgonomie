test("complete keyboard journey preserves answers on return, errors, revision, modification and confirmed restart", async ({ page }) => {
  await start(page)
  await expect(page.getByRole("heading", { level: 1 })).toBeFocused()
  await expect(page.getByRole("button", { name: "Retour", exact: true })).toBeDisabled()
  const answer = page.getByLabel("technical-answer", { exact: true })
  await answer.focus()
  await page.keyboard.type("value-1")
  await page.keyboard.press("Enter")
  await expect(page.getByRole("heading", { level: 2, name: "technical-step-2", exact: true })).toBeVisible()
  await expect(page.getByText("Étape 2 sur 3", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Retour", exact: true }).click()
  await expect(answer).toHaveValue("value-1")
  await answer.fill("")
  await page.getByTestId("validate-step").click()
  await expect(answer).toBeFocused()
  await expect(answer).toHaveAttribute("aria-invalid", "true")
  await expect(page.getByRole("alert")).toContainText("Renseignez une réponse")
  await answer.fill("value-1-corrected")
  await page.getByTestId("validate-step").click()
  await answer.fill("value-2")
  await page.getByTestId("validate-step").click()
  await expect(page.locator("main")).toHaveAttribute("data-view", "summary")
  await expect(page.getByText("2 / 2 étapes requises validées", { exact: true })).toBeVisible()
  await expect(page.getByText("value-1-corrected", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Modifier", exact: true }).click()
  await expect(page.locator("main")).toHaveAttribute("data-view", "journey")
  await page.locator('.answer-row[data-step-id="step-1"]').getByRole("button").click()
  await expect(answer).toBeFocused()
  await answer.fill("value-1-revised")
  await page.getByTestId("save-revision").click()
  await expect(page.locator("main")).toHaveAttribute("data-view", "journey")
  await page.getByRole("button", { name: "Voir la synthèse" }).click()
  await expect(page.getByText("value-1-revised", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Recommencer", exact: true }).click()
  await expect(page.getByRole("dialog")).toBeVisible()
  await expect(page.getByRole("button", { name: "Annuler", exact: true })).toBeFocused()
  await page.keyboard.press("Shift+Tab")
  await expect(page.getByRole("button", { name: "Confirmer et recommencer" })).toBeFocused()
  await page.keyboard.press("Tab")
  await expect(page.getByRole("button", { name: "Annuler", exact: true })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Recommencer", exact: true })).toBeFocused()
  await expect(page.getByText("value-1-revised", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Recommencer", exact: true }).click()
  await page.getByRole("button", { name: "Confirmer et recommencer" }).click()
  await expect(page.locator("main")).toHaveAttribute("data-view", "goal-selection")
  await expect(page.locator('input[type="radio"]:checked')).toHaveCount(0)
  await page.getByRole("radio", { name: "technical-objective-1", exact: false }).check()
  await page.getByRole("button", { name: "Commencer", exact: true }).click()
  await expect(answer).toHaveValue("")
  await expect(page.getByTestId("invalidated-answers")).toHaveCount(0)
  await expect(page.getByTestId("current-adaptation")).toHaveCount(0)
})

